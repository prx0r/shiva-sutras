#!/usr/bin/env python3
"""Essay-A master (Custom LA): essay-0 cells + six section openers + 76 A clips.
Reuses essence intermediates (bells/pads/cN_q/chant/t/p from l0_cuts — current
Fish voices, sheet==master). A clips cut from audio/*.mp3 per manifest beats.
Assembly grammar mirrors make_essence (afade 0.15, per-piece -21dB, 1.2s gaps,
water between sections, XL settle/terminal). Sheet asserts sheet==master.
Usage: python3 tools/make_custom_a.py  (repo root)
Outputs: audio/gen/custom_A.wav/.mp3 + build/LA_PRODUCTION.md (validate_sheet)."""
import json, os, re, sys

BASE = "/home/ubuntu/shiva-sutras"
os.chdir(BASE)
sys.path.insert(0, BASE + "/tools")
import make_essence as E  # noqa (cut/dur/sh/CUTS; no side effects on import)


def plays_p(t_text, p_text):
    n = lambda s: re.sub(r"[^a-z ]", "", s.lower()).strip()  # noqa
    return n(t_text) != n(p_text)


def main():
    CUTS = E.CUTS
    A = os.path.join(BASE, "audio", "gen", "custom_a_cuts")
    os.makedirs(A, exist_ok=True)
    seq = ["bowls_intro.wav"]
    sheet = []
    t = 0.0
    n = 0

    def push(f):
        nonlocal t, n
        d = E.dur(os.path.join(CUTS, f)) if not f.startswith("/") else E.dur(f)
        sheet.append((n + 1, t, d, f))
        t += d
        n += 1
        return f

    def row(cue, voice, notes):
        pass

    notes = {}
    CELLS = E.CELLS
    for s in range(1, 7):
        man = json.load(open(BASE + "/build/manifest_s%d_A.json" % s))
        card = man.get("card", {})
        q, tr, pl = man.get("question", ""), card.get("translation", ""), card.get("plain", "")
        tag = "c%d" % s
        # essay-0 cell for this section (the seed, full)
        br = "breath3.wav" if tag in ("c4", "c5") else "breath.wav"
        cp = f"{tag}_cell.wav"
        if not os.path.exists(os.path.join(CUTS, cp)):
            # single-span cells keep the span file (no _cell built)
            bi, bo = CELLS[s - 1][3][0]
            cp = f"{tag}_b0_{int(bi)}-{int(bo)}.wav"
        seq += ["long_break_bell.wav", f"{tag}_q.wav", br, f"{tag}_chant.wav",
                f"{tag}_t.wav", "tbeat.wav"]
        pp = [f"{tag}_p.wav"] if plays_p(tr, pl) else []
        seq += pp + ["gap.wav", cp, "water.wav"]
        notes[s] = "seed cell %s (essence-verified)" % tag
        # A clips
        beats = man.get("beats", [])
        assert beats, "no A beats S%d" % s
        for i, b in enumerate(beats):
            src = os.path.join(BASE, b["mp3"])
            assert os.path.exists(src), src
            dst = os.path.join(A, "a_s%d_%s_%d-%d.wav" % (s, b["uid"], int(b["t_in"]), int(b["t_out"])))
            E.cut(src, b["t_in"], b["t_out"], dst)
            seq += [os.path.basename(dst), "gap.wav"] if i < len(beats) - 1 else [os.path.basename(dst)]
        seq += ["water.wav"]
    seq += ["long_break_bell.wav", "xl6.wav"]

    # resolve to CUTS-relative or absolute for concat
    Ux = []
    for f in seq:
        p = os.path.join(CUTS, f)
        if os.path.exists(p):
            Ux.append(p)
            continue
        p2 = os.path.join(A, f)
        assert os.path.exists(p2), f
        Ux.append(p2)
    open("/tmp/opencode/custom_a.txt", "w").write("".join("file '%s'\n" % f for f in Ux))
    sh = E.sh
    sh(["ffmpeg", "-v", "error", "-y", "-f", "concat", "-safe", "0",
        "-i", "/tmp/opencode/custom_a.txt", "-af", "loudnorm=I=-16:TP=-1.5:LRA=11",
        f"{BASE}/audio/gen/custom_A.wav"])
    sh(["ffmpeg", "-v", "error", "-y", "-i", f"{BASE}/audio/gen/custom_A.wav",
        "-codec:a", "libmp3lame", "-q:a", "2", f"{BASE}/audio/gen/custom_A.mp3"])

    # sheet with measured timecodes (validate_sheet-compatible)
    L = []
    L.append("# LA — PRODUCTION SHEET (Essay A: essay-0 + six section arguments)")
    L.append("")
    L.append("Generated by `tools/make_custom_a.py` — opener stacks reused from essence")
    L.append("intermediates (`audio/gen/l0_cuts/`, Fish voices); A clips cut per")
    L.append("`build/manifest_s*_A.json` quote-located stamps. [FLAG] = ear-session decision.")
    L.append("")
    L.append("| # | t_in | dur | cue | voice | notes |")
    L.append("|---|---|---|---|---|---|")
    tt = 0.0
    cues = []
    for f in Ux:
        dd = E.dur(f)
        cues.append((tt, dd, os.path.basename(f)))
        tt += dd
    for i, (a, dd, f) in enumerate(cues, 1):
        v = "TTS" if re.search(r"_q\.wav|_t\.wav|_p\.wav", f) else (
            "Sharma" if "chant" in f or "head" in f else (
                "Baumer/dl1" if f.startswith("a_s") else "—"))
        L.append("| %d | %07.2f | %5.2f | `%s` | %s | |" % (i, a, dd, f, v))
    L.append("")
    L.append("**Total runtime: %.1f min (%.0fs). Rendered master must match within 1s.**"
             % (tt / 60, tt))
    L.append("")
    L.append("## Handover audit (voice-to-voice joints)")
    L.append("- bell→Q: OK (long_break_bell motto). Q→breath→chant: SOFT (tongue-switch).")
    L.append("- chant→T: OK (same verse, two tongues). T→P: OK or single-voiced (anti-echo rule).")
    L.append("- P→gap→archive voice: SOFT (timbre jump; fades + gap at ship).")
    L.append("- Archive→archive joins: audited in JOIN_AUDIT (55 OK / 9 SOFT / 0 WEAK at text level).")
    L.append("- Named bridges/soft spots (from JOIN_AUDIT): S1 thesis→speech-levels bridge;")
    L.append("  S2 Brahma-anchor glue; S4 iccha lever (demote candidate); S6 weight watch.")
    L.append("")
    L.append("## FX + pause vocabulary")
    L.append("- long_break_bell 4.7s section motto; breath 2.5s (3.0s c4/c5); tbeat 1.0s;")
    L.append("  gap 1.2s; water 2.5s; XL settle 5.0s open, terminal 6.0s close.")
    L.append("")
    L.append("## FLAGs (open, ear-session)")
    L.append("  OPEN [FLAG] S4 iccha (ss7-16) answers 'drives' not 'does' — demote-to-B lever.")
    L.append("  OPEN [FLAG] S6 weight — dancer promote (ss13-06) or re-ask lever.")
    L.append("  OPEN [FLAG] S1/S5 bridges land in audio (text-verdict: FLOWS).")
    open(f"{BASE}/build/LA_PRODUCTION.md", "w").write("\n".join(L) + "\n")

    master = E.dur(f"{BASE}/audio/gen/custom_A.mp3")
    print("LA: %d cues, sheet %.0fs, master %.1fs" % (len(cues), tt, master), flush=True)
    assert abs(tt - master) < 1.0, "SHEET/MASTER DIVERGED"
    print("SHEET == MASTER ✓", flush=True)


if __name__ == "__main__":
    main()
